// Turns the numbered migration files into one TypeScript module the server can
// import on every runtime (no file system at run time): src/schema/ts/migrations.sql.ts,
// an ordered array of {name, sql}. cf-worker applies the same files with
// `wrangler d1 migrations apply` (its wrangler.toml's migrations_dir).
const fs = require('fs');
const path = require('path');
const folder = process.argv[2];
const files = fs
	.readdirSync(folder)
	.filter((file) => /^\d{4}_.+\.sql$/.test(file))
	.sort();
const migrations = files.map((file) => ({
	name: file.replace(/\.sql$/, ''),
	sql: fs.readFileSync(path.join(folder, file), 'utf8'),
}));
fs.mkdirSync('./src/schema/ts', {recursive: true});
fs.writeFileSync(
	'./src/schema/ts/migrations.sql.ts',
	`// generated by sql2ts.cjs from ${folder}: do not edit\nexport default ${JSON.stringify(migrations, null, '\t')} as {name: string; sql: string}[];\n`,
);
